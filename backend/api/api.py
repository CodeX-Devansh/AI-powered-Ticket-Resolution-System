from datetime import datetime

from fastapi import Depends, FastAPI, HTTPException
from langgraph.types import Command
from sqlalchemy.orm import Session

from backend.config import get_db
from backend.graph.main import graph
from backend.graph.state import TicketState
from backend.model import Ticket
from backend.schema import TicketCreate, TicketReview


app = FastAPI()


@app.get("/health")
def health():
    return {
        "status": "ok"
    }

@app.post("/ticket")
def create_ticket(
    ticket: TicketCreate,
    db: Session = Depends(get_db)
):
    new_ticket = Ticket(
        ticket_id=generate_ticket_id(db),
        title=ticket.title,
        subject=ticket.subject,
        description=ticket.description,
        status="PENDING",
        category=None,
        priority=None,
        confidence_score=None,
        resolution=None,
    )

    db.add(new_ticket)
    db.commit()
    db.refresh(new_ticket)

    return new_ticket

@app.put("/ticket/{ticket_id}/process")
def process_ticket(
    ticket_id: str,
    db: Session = Depends(get_db)
):
    db_ticket = (
        db.query(Ticket)
        .filter(Ticket.ticket_id == ticket_id)
        .first()
    )

    if not db_ticket:
        raise HTTPException(
            status_code=404,
            detail="Ticket not found"
        )

    if db_ticket.status == "RESOLVED":
        return {
            "message": "Ticket already resolved",
            "ticket_id": ticket_id,
            "status": db_ticket.status
        }

    initial_state: TicketState = {
        "ticket_id": db_ticket.ticket_id,
        "title": db_ticket.title,
        "subject": db_ticket.subject,
        "description": db_ticket.description,
    }

    result = graph.invoke(
        initial_state,
        config={
            "configurable": {
                "thread_id": ticket_id
            }
        }
    )

    db_ticket.category = result.get("category")
    db_ticket.priority = result.get("priority")
    db_ticket.confidence_score = result.get(
        "confidence_score"
    )

    requires_human_review = result.get(
        "requires_human_review",
        False
    )

    if requires_human_review:

        db_ticket.status = "PENDING"

        db.commit()
        db.refresh(db_ticket)

        return {
            "message": "Human review required",
            "ticket_id": ticket_id,
            "status": db_ticket.status,
            "category": db_ticket.category,
            "priority": db_ticket.priority,
            "confidence_score": db_ticket.confidence_score,
            "requires_human_review": True,
            "proposed_resolution": result.get(
                "resolution"
            ),
        }

    final_resolution = result.get(
        "final_resolution"
    )

    if not final_resolution:
        final_resolution = result.get(
            "resolution"
        )

    if not final_resolution:
        raise HTTPException(
            status_code=500,
            detail="No resolution generated by the workflow."
        )

    db_ticket.resolution = final_resolution
    db_ticket.status = "RESOLVED"

    db.commit()
    db.refresh(db_ticket)

    return {
        "message": "Ticket resolved automatically",
        "ticket_id": ticket_id,
        "status": db_ticket.status,
        "category": db_ticket.category,
        "priority": db_ticket.priority,
        "confidence_score": db_ticket.confidence_score,
        "requires_human_review": False,
        "resolution": db_ticket.resolution,
    }


@app.put("/ticket/{ticket_id}/review")
def review_ticket(
    ticket_id: str,
    review: TicketReview,
    db: Session = Depends(get_db)
):
    db_ticket = (
        db.query(Ticket)
        .filter(Ticket.ticket_id == ticket_id)
        .first()
    )

    if not db_ticket:
        raise HTTPException(
            status_code=404,
            detail="Ticket not found"
        )

    if db_ticket.status == "RESOLVED":
        raise HTTPException(
            status_code=400,
            detail="Ticket is already resolved"
        )

    if review.action == "modify":

        if not review.resolution:
            raise HTTPException(
                status_code=400,
                detail=(
                    "Modified resolution is required "
                    "when action is 'modify'."
                )
            )

        if not review.resolution.strip():
            raise HTTPException(
                status_code=400,
                detail="Modified resolution cannot be empty."
            )


    resume_data = {
        "action": review.action,
        "resolution": review.resolution,
        "comment": review.comment,
    }

    result = graph.invoke(
        Command(
            resume=resume_data
        ),
        config={
            "configurable": {
                "thread_id": ticket_id
            }
        }
    )

    final_resolution = result.get(
        "final_resolution"
    )

    if not final_resolution:
        raise HTTPException(
            status_code=500,
            detail="Final resolution was not generated."
        )


    db_ticket.resolution = final_resolution
    db_ticket.status = "RESOLVED"

    db.commit()
    db.refresh(db_ticket)

    return {
        "message": "Human review completed",
        "ticket_id": ticket_id,
        "status": db_ticket.status,
        "resolution": db_ticket.resolution,
        "review_status": result.get(
            "human_review_status"
        ),
        "review_comment": result.get(
            "human_review_comment"
        ),
    }


