def generate_ticket_id(
    db: Session
) -> str:

    today_str = datetime.now().strftime("%Y%m%d")

    prefix = f"INC-{today_str}-"

    last_ticket = (
        db.query(Ticket.ticket_id)
        .filter(
            Ticket.ticket_id.like(
                f"{prefix}%"
            )
        )
        .order_by(
            Ticket.id.desc()
        )
        .first()
    )

    if last_ticket:

        last_seq = int(
            last_ticket[0].split("-")[-1]
        )

        new_seq = last_seq + 1

    else:

        new_seq = 1

    return f"{prefix}{new_seq:04d}"